"""Defaulter PDF generation for college notice boards using ReportLab (Prompt N11)."""

from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any, Dict, List
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle


def _sanitize_csv_formula_injection(text: str) -> str:
    """Escape any leading formula trigger (=, +, -, @) to prevent injection."""
    s = str(text or "")
    if s.startswith(("=", "+", "-", "@")):
        return f"'{s}"
    return s


def generate_defaulter_pdf(
    defaulters: List[Dict[str, Any]],
    admin_id: str,
    threshold: float = 75.0,
) -> bytes:
    """Generate official Notice Board PDF report listing defaulters grouped by branch."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=18,
        leading=22,
        alignment=1,  # Center
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=10,
    )
    sub_style = ParagraphStyle(
        "DocSub",
        parent=styles["Normal"],
        fontSize=10,
        leading=14,
        alignment=1,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=15,
    )
    branch_heading_style = ParagraphStyle(
        "BranchHeading",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#0f172a"),
        spaceBefore=12,
        spaceAfter=6,
    )
    cell_style = ParagraphStyle(
        "Cell",
        parent=styles["Normal"],
        fontSize=9,
        leading=11,
    )
    footer_style = ParagraphStyle(
        "Footer",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        alignment=2,  # Right
        textColor=colors.HexColor("#94a3b8"),
        spaceBefore=20,
    )

    elements = []

    # Title & Header
    gen_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    elements.append(Paragraph("ROLLCALL AI — OFFICIAL DEFAULTERS LIST", title_style))
    elements.append(Paragraph(f"Generated: {gen_time} &bull; Attendance Threshold: &lt; {threshold:.1f}%", sub_style))
    elements.append(Spacer(1, 10))

    # Group by branch
    branches: Dict[str, List[Dict[str, Any]]] = {}
    for d in defaulters:
        b = d.get("branch") or "General"
        branches.setdefault(b, []).append(d)

    if not branches:
        elements.append(Paragraph("<i>No students currently fall below the attendance threshold.</i>", sub_style))
    else:
        for b_name in sorted(branches.keys()):
            elements.append(Paragraph(f"Department / Branch: <b>{b_name}</b>", branch_heading_style))
            
            table_data = [
                ["USN", "Student Name", "Attended / Conducted", "Attendance %", "Classes Needed"]
            ]
            
            for s in branches[b_name]:
                clean_name = _sanitize_csv_formula_injection(s.get("name", ""))
                table_data.append([
                    Paragraph(s.get("usn", ""), cell_style),
                    Paragraph(clean_name, cell_style),
                    f"{s.get('attended', 0)} / {s.get('conducted', 0)}",
                    f"{s.get('percent', 0.0):.1f}%",
                    str(s.get("classes_needed", 0)),
                ])

            col_widths = [100, 160, 120, 80, 80]
            t = Table(table_data, colWidths=col_widths)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#334155")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, 0), 9),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
                ("TOPPADDING", (0, 0), (-1, 0), 6),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("ALIGN", (2, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]))
            elements.append(t)
            elements.append(Spacer(1, 10))

    # Overall Summary
    total_defaulters = len(defaulters)
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(f"<b>Overall Summary:</b> Total defaulters across all branches: <b>{total_defaulters}</b>", cell_style))
    elements.append(Paragraph(f"Generated by administrator: <b>{_sanitize_csv_formula_injection(admin_id)}</b>", footer_style))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()

