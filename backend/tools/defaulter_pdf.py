"""N11: Defaulter PDF report for the notice board.

Generates an official PDF report of students below the attendance threshold
using ReportLab, and writes a ``DEFAULTER_EXPORT`` row to the append-only
audit log. ADMIN only at the API layer.

Colour bands in the report are class-health indicators (green > 85,
yellow 70-85, red < 70), never eligibility decisions.
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from io import BytesIO
from typing import Any, Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.config import DEFAULTER_REQUIRED_PERCENT, DEFAULTER_THRESHOLD_PERCENT
from app.db import crud
from tools.defaulter_tool import defaulters

logger = logging.getLogger("rollcall.tools.defaulter_pdf")

_SPREADSHEET_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def _safe_text(value: Any) -> str:
    """Neutralize spreadsheet/PDF formula prefixes and coerce to text."""
    if value is None:
        return ""
    text = str(value)
    if text.startswith(_SPREADSHEET_FORMULA_PREFIXES):
        return "'" + text
    return text


def generate_defaulter_pdf(
    db: Any,
    actor_id: str,
    actor_role: str,
    subject_code: Optional[str] = None,
    branch: Optional[str] = None,
    semester: Optional[str] = None,
    threshold: float = DEFAULTER_THRESHOLD_PERCENT,
) -> bytes:
    """Build the defaulter PDF and return it as bytes.

    The caller is responsible for the ADMIN role check; this function always
    computes unscoped institutional data and records who exported it.
    """
    result = defaulters(
        db=db,
        actor_id=actor_id,
        actor_role="ADMIN",
        assigned_subjects=None,
        subject_code=subject_code,
        branch=branch,
        semester=semester,
        threshold=threshold,
        required_percent=DEFAULTER_REQUIRED_PERCENT,
    )

    students: List[Dict[str, Any]] = result.get("students", [])
    defaulters_only = [s for s in students if s.get("is_defaulter")]
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=0.7 * inch,
        rightMargin=0.7 * inch,
        topMargin=0.7 * inch,
        bottomMargin=0.7 * inch,
        title="RollCall AI - Defaulter Report",
        author="RollCall AI",
    )
    styles = getSampleStyleSheet()
    story: List[Any] = [
        Paragraph("Defaulter Report", styles["Title"]),
        Spacer(1, 0.12 * inch),
        Paragraph(f"Generated (UTC): {generated_at}", styles["Normal"]),
        Paragraph(f"Generated by: {_safe_text(actor_id)} ({_safe_text(actor_role)})", styles["Normal"]),
        Paragraph(f"Threshold: strictly below {threshold:.1f}%", styles["Normal"]),
        Paragraph(f"Students analysed: {result.get('total_students', 0)}", styles["Normal"]),
        Paragraph(f"Defaulters: {result.get('defaulter_count', 0)}", styles["Normal"]),
        Spacer(1, 0.18 * inch),
    ]

    if defaulters_only:
        data = [["USN", "Name", "Branch", "Attended", "Conducted", "Percent", "Needed"]]
        for s in defaulters_only:
            data.append(
                [
                    _safe_text(s.get("usn")),
                    _safe_text(s.get("name")),
                    _safe_text(s.get("branch")),
                    str(s.get("attended", 0)),
                    str(s.get("conducted", 0)),
                    f"{float(s.get('percent', 0.0)):.1f}%",
                    str(s.get("classes_needed", 0)),
                ]
            )

        table = Table(
            data,
            colWidths=[0.95 * inch, 1.35 * inch, 0.75 * inch, 0.75 * inch, 0.9 * inch, 0.75 * inch, 0.65 * inch],
            repeatRows=1,
        )
        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#3d3d3d")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f4f4")]),
                    ("ALIGN", (3, 0), (-1, -1), "CENTER"),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ]
            )
        )
        story.append(table)
    else:
        story.append(Paragraph("No students are below the threshold.", styles["Normal"]))

    story.append(Spacer(1, 0.25 * inch))
    story.append(
        Paragraph(
            "RollCall AI - Defaulter Report. Colour bands show class health "
            "(green above 85, yellow 70 to 85, red below 70), not eligibility.",
            styles["Italic"],
        )
    )

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    try:
        crud.create_audit_entry(
            db,
            actor_id=actor_id,
            actor_role=actor_role,
            action="DEFAULTER_EXPORT",
            entity_type="defaulter_report",
            entity_id=f"defaulters_{generated_at}",
            new_value=(
                f"defaulters={result.get('defaulter_count', 0)};"
                f"total={result.get('total_students', 0)};threshold={threshold}"
            ),
            reason="Defaulter PDF report generated",
            timestamp=generated_at,
        )
        db.commit()
    except Exception as exc:  # pragma: no cover - defensive
        # An audit failure must not destroy a report that was already built.
        logger.warning("Defaulter export audit failed: %s", exc)
        try:
            db.rollback()
        except Exception:
            pass

    return pdf_bytes


__all__ = ["generate_defaulter_pdf"]
