import { apiClient } from "@/services/api/client";
import type {
  VerifiedSessionPage,
  VerifiedSummaryReport,
  VerifiedAgentResponse,
} from "@/types/dashboard";

export interface DashboardData {
  sessions: VerifiedSessionPage | null;
  overallAnalytics: VerifiedSummaryReport | null;
  todayAnalytics: VerifiedSummaryReport | null;
  teacherMappings: Array<{ teacher_id: string; subject_code: string }> | null;
}

export async function fetchDashboardData(
  todayIsoDate: string,
  options?: { includeTeacherMappings?: boolean }
): Promise<DashboardData> {
  const requests: Array<Promise<unknown>> = [
    apiClient.get<VerifiedSessionPage>("/api/v1/sessions", { limit: 100 }),
    apiClient.get<VerifiedSummaryReport>("/api/v1/analytics/overview"),
    apiClient.get<VerifiedSummaryReport>(`/api/v1/analytics/date/${todayIsoDate}/summary`),
  ];

  // The teacher/subject mapping list is an administrator only endpoint. It is
  // only requested for administrators so faculty users never trigger a 403.
  const mappingsRequest = options?.includeTeacherMappings
    ? apiClient.get<{ items: Array<{ teacher_id: string; subject_code: string }> }>(
        "/api/v1/admin/teacher-subjects"
      )
    : Promise.resolve({ items: [] as Array<{ teacher_id: string; subject_code: string }> });

  const [sessionsRes, overallRes, todayRes, mappingsRes] = await Promise.allSettled([
    ...requests,
    mappingsRequest,
  ]);

  return {
    sessions: sessionsRes.status === "fulfilled" ? (sessionsRes.value as VerifiedSessionPage) : null,
    overallAnalytics:
      overallRes.status === "fulfilled" ? (overallRes.value as VerifiedSummaryReport) : null,
    todayAnalytics:
      todayRes.status === "fulfilled" ? (todayRes.value as VerifiedSummaryReport) : null,
    teacherMappings:
      mappingsRes.status === "fulfilled"
        ? ((mappingsRes.value as { items: Array<{ teacher_id: string; subject_code: string }> })
            .items ?? [])
        : null,
  };
}

export async function sendAgentQuery(
  query: string,
  sessionId?: string
): Promise<VerifiedAgentResponse> {
  return apiClient.post<VerifiedAgentResponse>("/api/v1/agent/chat", {
    query,
    session_id: sessionId || undefined,
  });
}

export async function uploadAttendanceFile(
  file: File,
  sessionId?: string
): Promise<VerifiedAgentResponse> {
  const formData = new FormData();
  formData.append("file", file);
  if (sessionId) {
    formData.append("session_id", sessionId);
  }
  // The multipart Content-Type (including the boundary) is generated by the
  // browser - the shared API client removes the JSON default header.
  return apiClient.post<VerifiedAgentResponse>("/api/v1/agent/process-file", formData);
}

