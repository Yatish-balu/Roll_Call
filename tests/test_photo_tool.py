class TestPreprocessImage:
    def test_loads_and_returns_rgb_and_thresh(self, white_image):
        rgb, thresh = preprocess_image(white_image)
        assert isinstance(rgb, np.ndarray)
        assert isinstance(thresh, np.ndarray)
        assert rgb.ndim == 3 and rgb.shape[2] == 3   # RGB
        assert thresh.ndim == 2                        # grayscale binary

    def test_raises_file_not_found(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            preprocess_image(tmp_path / "nonexistent.jpg")

    def test_raises_value_error_for_invalid_image(self, tmp_path):
        bad = tmp_path / "bad.jpg"
        bad.write_bytes(b"not-an-image")
        with pytest.raises(ValueError, match="OpenCV could not decode"):
            preprocess_image(bad)

    def test_output_shape_matches_input(self, attendance_image):
        original = cv2.imread(str(attendance_image))
        rgb, thresh = preprocess_image(attendance_image)
        # Width/height may differ slightly after deskew but not drastically
        assert abs(rgb.shape[0] - original.shape[0]) < 20
        assert abs(rgb.shape[1] - original.shape[1]) < 20

    def test_thresh_is_binary(self, attendance_image):
        _, thresh = preprocess_image(attendance_image)
        unique_vals = set(np.unique(thresh))
        assert unique_vals.issubset({0, 255}), f"Non-binary values in thresh: {unique_vals}"


class TestDetectSkewAngle:
    def test_horizontal_image_has_near_zero_angle(self):
        # A perfectly horizontal line → angle close to 0
        img = np.ones((200, 600), dtype=np.uint8) * 255
        cv2.line(img, (10, 100), (590, 100), 0, 3)
        angle = _detect_skew_angle(img)
        assert abs(angle) < 5.0

    def test_returns_float(self):
        blank = np.ones((100, 100), dtype=np.uint8) * 255
        angle = _detect_skew_angle(blank)
        assert isinstance(angle, float)

    def test_sparse_image_returns_zero(self):
        sparse = np.zeros((100, 100), dtype=np.uint8)
        angle = _detect_skew_angle(sparse)
        assert angle == 0.0


class TestRotateImage:
    def test_colour_image_rotation(self):
        img = np.zeros((100, 200, 3), dtype=np.uint8)
        cv2.rectangle(img, (50, 40), (150, 60), (0, 0, 255), -1)
        rotated = _rotate_image(img, 10)
        assert rotated.shape[2] == 3
        assert rotated.shape != (0, 0, 3)

    def test_grayscale_rotation(self):
        gray = np.ones((100, 200), dtype=np.uint8) * 128
        rotated = _rotate_image(gray, -5)
        assert rotated.ndim == 2

    def test_zero_angle_unchanged_dimensions(self):
        img = np.ones((100, 200, 3), dtype=np.uint8) * 200
        rotated = _rotate_image(img, 0.0)
        assert rotated.shape == img.shape


class TestImageToBase64:
    def test_returns_non_empty_string(self, white_image):
        rgb, _ = preprocess_image(white_image)
        b64, mime = _image_to_base64(rgb)
        assert isinstance(b64, str) and len(b64) > 100
        assert mime == "image/jpeg"

    def test_decodable(self, white_image):
        import base64
        rgb, _ = preprocess_image(white_image)
        b64, _ = _image_to_base64(rgb)
        decoded = base64.b64decode(b64)
        arr = np.frombuffer(decoded, dtype=np.uint8)
        img = cv2.imdecode(arr, cv2.IMREAD_COLOR)
        assert img is not None


