def _make_white_image_file(tmp_path: Path, name: str = "test.jpg") -> Path:
    """Create a small white JPEG in tmp_path."""
    img = np.ones((200, 600, 3), dtype=np.uint8) * 255
    path = tmp_path / name
    cv2.imwrite(str(path), img)
    return path


def _make_attendance_image_file(tmp_path: Path, name: str = "attendance.jpg") -> Path:
    """Create a simple synthetic attendance sheet image."""
    try:
        from PIL import ImageFont
        font = ImageFont.load_default()
    except Exception:
        font = None

    img_pil = Image.new("RGB", (600, 250), color=(255, 255, 255))
    draw = ImageDraw.Draw(img_pil)
    rows = [
        "#  USN           Student Name       Status",
        "1  1MS21CS001    Alice Smith        ✓",
        "2  1MS21CS002    Bob Jones          ✗",
        "3  1MS21CS003    Charlie Brown      ✓",
    ]
    y = 10
    for row in rows:
        draw.text((10, y), row, fill=(0, 0, 0), font=font)
        y += 30

    path = tmp_path / name
    img_pil.save(str(path))
    return path


