class TestParseAndValidateJson:
    def _valid_json(self):
        return json.dumps([
            {"usn": "1MS21CS001", "name": "Alice", "status": "present", "confidence": 0.95},
            {"usn": "1MS21CS002", "name": "Bob",   "status": "absent",  "confidence": 0.90},
        ])

    def test_parses_valid_json(self):
        warn: List[str] = []
        rows = _parse_and_validate_json(self._valid_json(), 0.5, ExtractionSource.LLM, warn)
        assert len(rows) == 2
        assert rows[0].usn == "1MS21CS001"
        assert rows[0].status == "PRESENT"
        assert rows[1].status == "ABSENT"
        assert not warn

    def test_strips_markdown_fences(self):
        raw = "```json\n" + self._valid_json() + "\n```"
        warn: List[str] = []
        rows = _parse_and_validate_json(raw, 0.5, ExtractionSource.LLM, warn)
        assert len(rows) == 2

    def test_skips_row_missing_usn(self):
        data = json.dumps([
            {"name": "No USN", "status": "present", "confidence": 0.9},
            {"usn": "1MS21CS001", "name": "Alice", "status": "absent", "confidence": 0.9},
        ])
        warn: List[str] = []
        rows = _parse_and_validate_json(data, 0.5, ExtractionSource.LLM, warn)
        assert len(rows) == 1
        assert rows[0].usn == "1MS21CS001"
        assert any("missing USN" in w for w in warn)

    def test_low_confidence_forces_unreviewed(self):
        data = json.dumps([
            {"usn": "1MS21CS001", "name": "Alice", "status": "PRESENT", "confidence": 0.3},
        ])
        warn: List[str] = []
        rows = _parse_and_validate_json(data, 0.5, ExtractionSource.LLM, warn)
        assert len(rows) == 1
        assert rows[0].status == "UNREVIEWED"
        assert any("UNREVIEWED" in w for w in warn)

    def test_unknown_status_becomes_unreviewed(self):
        data = json.dumps([
            {"usn": "1MS21CS001", "name": "Alice", "status": "EXCUSED", "confidence": 0.9},
        ])
        warn: List[str] = []
        rows = _parse_and_validate_json(data, 0.5, ExtractionSource.LLM, warn)
        assert rows[0].status == "UNREVIEWED"

    def test_raises_on_invalid_json(self):
        with pytest.raises(ValueError, match="JSON parse failed"):
            _parse_and_validate_json("{not valid json", 0.5, ExtractionSource.LLM, [])

    def test_raises_on_non_array_json(self):
        with pytest.raises(ValueError, match="Expected a JSON array"):
            _parse_and_validate_json('{"usn": "abc"}', 0.5, ExtractionSource.LLM, [])

    def test_pending_alias_preserved(self):
        data = json.dumps([
            {"usn": "1MS21CS001", "name": "Alice", "status": "pending", "confidence": 0.9},
        ])
        rows = _parse_and_validate_json(data, 0.5, ExtractionSource.LLM, [])
        assert rows[0].status == "PENDING"

    def test_unreviewed_alias_preserved(self):
        data = json.dumps([
            {"usn": "1MS21CS001", "name": "Alice", "status": "ambiguous", "confidence": 0.9},
        ])
        rows = _parse_and_validate_json(data, 0.5, ExtractionSource.LLM, [])
        assert rows[0].status == "UNREVIEWED"

    def test_all_rows_empty_returns_empty_list(self):
        rows = _parse_and_validate_json("[]", 0.5, ExtractionSource.LLM, [])
        assert rows == []


